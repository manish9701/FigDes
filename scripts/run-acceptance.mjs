#!/usr/bin/env node
/**
 * Issue #13 acceptance-matrix runner.
 *
 * The sibling of `run-stress-matrix.mjs`, and deliberately the same shape: one
 * case per acceptance-gate line, an explicit status, and a report that is
 * generated rather than written.
 *
 *   artifacts/acceptance/latest.json   machine-readable
 *   docs/issue-13-report.md            the readable record, checked in
 *
 * Offline by construction. L01-L03 need a write to a disposable frame in the
 * live file and report BLOCKED rather than PASS, because claiming a render
 * nobody produced is the one thing this whole suite exists to prevent.
 *
 * Usage: npm run acceptance
 *        npm run acceptance -- --strict   (exit 1 on any failure)
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { runMatrix, summarise, CASES, BLOCKED_CASES, OPEN_CASES } from "../tests/issue-13-matrix.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = resolve(root, process.env.FIGDES_ACCEPTANCE_OUTPUT ?? "artifacts/acceptance/latest.json");
const mdPath = resolve(root, "docs/issue-13-report.md");

const results = runMatrix();
const totals = summarise(results);
const now = new Date().toISOString();

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();

const table = (rows) =>
  [
    "| ID | Case | Status | Measured result |",
    "| --- | --- | --- | --- |",
    ...rows.map((r) => `| **${r.id}** | ${cell(r.title)} | ${r.status} | ${cell(r.detail)} |`),
    "",
  ].join("\n");

const openDetail = results
  .filter((r) => r.status === "FAIL")
  .map((r) => {
    const c = OPEN_CASES.find((x) => x.id === r.id);
    return [
      `### ${r.id} — ${r.title}`,
      "",
      `**Requirement.** ${r.requirement}`,
      "",
      `**Known issue.** ${c?.knownIssue ?? "Not recorded — that is a bug in the matrix itself."}`,
      "",
      `**Measured.** ${r.detail}`,
      "",
      "```json",
      JSON.stringify(r.raw, null, 2),
      "```",
      "",
    ].join("\n");
  })
  .join("\n");

const md = `# Issue #13 — acceptance report

Generated by \`npm run acceptance\` on ${now}. Do not edit by hand; edit
\`tests/issue-13-matrix.mjs\` and regenerate.

**${totals.total} cases — ${totals.pass} PASS, ${totals.fail} FAIL, ${totals.blocked} BLOCKED.**

One case per acceptance-gate line in the issue, plus the review-engine and
control cases the gate also names. Each has a stable id, a deterministic input
built from literals, a measured result and an explicit status. This runner is
offline: no result here is a live render or a live apply.

## Acceptance gate

${table(results.filter((r) => r.group === "compiler"))}## Review engine

${table(results.filter((r) => r.group === "guardrails"))}## Live render/apply gate

${table(results.filter((r) => r.group === "live"))}
These need a write to a disposable frame in the live file and a read back. They
report BLOCKED and claim no evidence. No operations have been applied to the
Exo Labs file.

## Open failures

${openDetail || "_None. Every case passes._"}

## Keeping this honest

- Every case in \`CASES\` must report PASS and every case in \`OPEN_CASES\` must
  still report FAIL. A silent fix fails CI and forces the issue to be closed
  deliberately instead of quietly.
- A PASS must carry a non-empty raw payload; a BLOCKED must say why and claim no
  evidence. Both asserted.
- The issue's own X04 and X06 cases are here even though they already passed —
  a guardrail that stops firing is as much a regression as one that starts, and
  "it passes today" is the belief that lets it rot.
- \`npm test\` runs this alongside the #12 matrix and the rest of the suite.
`;

await mkdir(dirname(jsonPath), { recursive: true });
await writeFile(jsonPath, JSON.stringify({ generatedAt: now, totals, results }, null, 2));
await mkdir(dirname(mdPath), { recursive: true });
await writeFile(mdPath, md);

console.log(`acceptance: ${totals.pass} PASS, ${totals.fail} FAIL, ${totals.blocked} BLOCKED (${totals.total} total)`);
console.log(`  cases   ${CASES.length} passing, ${OPEN_CASES.length} open, ${BLOCKED_CASES.length} blocked`);
for (const r of results.filter((x) => x.status === "FAIL")) console.log(`  FAIL    ${r.id}: ${r.detail.slice(0, 110)}`);
console.log(`  json    ${jsonPath}`);
console.log(`  report  ${mdPath}`);

if (process.argv.includes("--strict")) process.exit(totals.fail > 0 ? 1 : 0);
